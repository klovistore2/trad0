export function translator(language: Language) {
  const table = translations[language];
  return (key: StringKey, values: Record<string, string | number> = {}) =>
    (table?.[key] ?? en[key]).replace(/\{(\w+)\}/g, (match, name: string) => name in values ? String(values[name]) : match);
}
// Keys a language still reads in English. Every offered language is expected to have none.
export function untranslated(language: Language): StringKey[] {
  if (language === "en") return [];
  const table = translations[language] ?? {};
  return (Object.keys(en) as StringKey[]).filter(key => !table[key]?.trim());
}
export type Translate = ReturnType<typeof translator>;
